// Reads every mirrored PDF under public/docs/ and emits
// src/data/docMeta.js — a map from public-relative path to
// { pages, sizeBytes }. Runs as part of the build so the Documents
// page can show real page count + file size next to each source that
// has a localCopy, without estimating.
//
// Extraction rules:
//   - sizeBytes: fs.statSync(...).size
//   - pages: max of every "/Count N" in the raw PDF stream. The PDF
//     spec puts the total leaf-page count in the Pages tree root as
//     /Count, and that count is always ≥ any intermediate node's
//     count, so max() picks the root even when the root object is
//     serialized late in the file.
//
// Re-run when a mirrored PDF is added, removed, or replaced:
//   node scripts/extract-doc-meta.js
// (also runs automatically as part of `npm run build`).
import { readFileSync, statSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DOCS_DIR = join(ROOT, 'public', 'docs')
const OUT_FILE = join(ROOT, 'src', 'data', 'docMeta.js')

function pageCount(buffer) {
  const text = buffer.toString('latin1')
  const counts = [...text.matchAll(/\/Count\s+(\d+)/g)].map(m => parseInt(m[1], 10))
  if (counts.length) return Math.max(...counts)
  // Fallback if /Count is absent (rare, non-conforming PDFs).
  const leaves = text.match(/\/Type\s*\/Page(?!s)/g) || []
  return leaves.length
}

const entries = readdirSync(DOCS_DIR)
  .filter(f => f.toLowerCase().endsWith('.pdf'))
  .sort()
  .map(f => {
    const abs = join(DOCS_DIR, f)
    const buf = readFileSync(abs)
    const st = statSync(abs)
    return [`/docs/${f}`, { pages: pageCount(buf), sizeBytes: st.size }]
  })

const body =
`// GENERATED by scripts/extract-doc-meta.js — do not edit by hand.
// Regenerate with: node scripts/extract-doc-meta.js
// Sources.jsx reads this map, keyed by the source's localCopy path.
export const docMeta = {
${entries.map(([k, v]) => `  ${JSON.stringify(k)}: { pages: ${v.pages}, sizeBytes: ${v.sizeBytes} },`).join('\n')}
}
`

writeFileSync(OUT_FILE, body)
console.log(`extract-doc-meta: wrote ${entries.length} entries to src/data/docMeta.js`)
for (const [k, v] of entries) console.log(`  ${k}  ${v.pages} pages  ${v.sizeBytes} bytes`)
